import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { appendFile, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import test from 'node:test';
import { verifyCodexWakeEvidence } from '../bin/codex-wake-evidence.mjs';
import { createAppServer } from './fixtures/fake-app-server.mjs';

const exec = promisify(execFile);
const thread = '22222222-2222-4222-8222-222222222222';
const turn = '33333333-3333-4333-8333-333333333333';
const correlation = 'waker-44444444-4444-4444-8444-444444444444';
const bin = fileURLToPath(new URL('../bin/codex-wake-evidence.mjs', import.meta.url));
const graph = fileURLToPath(new URL('../bin/mesh-graph.mjs', import.meta.url));

test('queued wake needs explicit apply, a native start and durable correlated proof', async t => {
  const root = await mkdtemp(join(tmpdir(), 'wake-evidence-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const state = join(root, 'graph'), evidence = join(root, 'evidence'), socket = join(root, 'fake.sock');
  await mkdir(state, { mode: 0o700 }); await mkdir(evidence, { mode: 0o700 });
  const call = async (...args) => JSON.parse((await exec(process.execPath, [graph, '--state', state, ...args])).stdout);
  await call('add', '--agent', 'codex', '--tmux-target', 'fixture', '--cwd', '/synthetic', '--runtime-uuid', thread, '--json');
  await call('migrate', '--apply', '--json');
  const session = `codex:${thread}`;
  async function prepareChannel(name, nativeId = 'queued-1') {
    await call('channel', 'create', '--name', name, '--session', session);
    await call('channel', 'enqueue', '--name', name, '--id', correlation, '--input', 'fixture');
    await call('channel', 'begin-delivery', '--name', name, '--id', correlation, '--session', session, '--generation', '1');
    await call('channel', 'acknowledge', '--name', name, '--id', correlation, '--input', JSON.stringify({ status: 'accepted', messageId: correlation, session, generation: 1, nativeQueueId: nativeId }));
  }
  await prepareChannel('success');
  const cursor = (await call('query', 'changes', '--input', JSON.stringify({ initial: 'head' }))).cursor;
  const requests = []; let mode = 'success', nativeId = 'queued-1', autoReservedMs = 0, delayedReads = 0;
  const server = createAppServer((request, peer) => {
    if (!request.id) return;
    requests.push(request);
    if (request.method === 'thread/queue/list') peer.send({ id: request.id, result: { data: mode === 'auto-drained' ? [] : [{ id: nativeId, clientUserMessageId: mode === 'wrong' ? 'wrong' : correlation, input: [{ type: 'text', text: mode === 'wrong-queue-payload' ? 'different' : 'fixture', text_elements: [] }] }], nextCursor: null } });
    else if (request.method === 'thread/queue/start') peer.send({ id: request.id, result: { turn: { id: turn, status: mode === 'uncertain' ? 'completed' : 'inProgress', startedAt: mode === 'null-start' ? null : 123456789, items: [] } } });
    else if (request.method === 'thread/read' && request.params.includeTurns === false) peer.send({ id: request.id, result: { thread: { id: thread, status: { type: mode === 'busy' ? 'active' : 'idle' } } } });
    else if (request.method === 'thread/read' && mode === 'null-start' && delayedReads++ === 0) peer.send({ id: request.id, result: { thread: { id: thread, turns: [{ id: turn, startedAt: null, itemsView: 'full', items: [] }] } } });
    else if (request.method === 'thread/read') peer.send({ id: request.id, result: { thread: { id: mode === 'wrong-thread' ? turn : thread, turns: [{ id: mode === 'wrong-turn' ? thread : turn, status: 'completed', startedAt: mode === 'wrong-time' ? 123456788 : mode === 'auto-same-second' ? Math.floor(autoReservedMs / 1000) : nativeId === 'queued-auto-proof' && mode !== 'auto-old-turn' ? Math.floor(Date.now() / 1000) : 123456789, itemsView: mode === 'partial' ? 'summary' : 'full', items: [{ type: 'userMessage', id: 'msg-1', startedAtMs: nativeId === 'queued-auto-proof' ? Date.now() : 123456789001, clientId: mode === 'wrong-client' ? 'other' : correlation, content: [{ type: 'text', text: mode === 'wrong-input' ? 'different' : 'fixture', text_elements: [] }] }] }] } } });
    else peer.send({ id: request.id, result: {} });
  });
  await new Promise(resolve => server.listen(socket, resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const env = { ...process.env, CODEX_REMOTE_SOCK: socket, CODEX_NO_REMOTE: '' };
  const args = ['--thread', thread, '--queue-id', 'queued-1', '--correlation', correlation, '--channel', 'success', '--generation', '1', '--evidence-root', evidence, '--graph-state', state];
  mode = 'busy';
  const busy = JSON.parse((await exec(process.execPath, [bin, '--preflight', '--thread', thread, '--queue-id', 'queued-1', '--correlation', correlation], { env })).stdout);
  assert.equal(busy.status, 'not-ready');
  const beforeBusy = requests.filter(r => r.method === 'thread/queue/start').length;
  await assert.rejects(exec(process.execPath, [bin, '--apply', ...args], { env }));
  assert.equal(requests.filter(r => r.method === 'thread/queue/start').length, beforeBusy);
  assert.equal((await call('channel', 'get', '--name', 'success')).channel.wakeReservation, undefined);
  mode = 'success'; requests.length = 0;
  await assert.rejects(exec(process.execPath, [bin, ...args], { env }));
  assert.equal(requests.length, 0);
  await prepareChannel('handover');
  await call('channel', 'begin-handover', '--name', 'handover');
  await assert.rejects(exec(process.execPath, [bin, '--apply', '--thread', thread, '--queue-id', 'queued-1', '--correlation', correlation, '--channel', 'handover', '--generation', '1', '--evidence-root', evidence, '--graph-state', state], { env }));
  assert.equal(requests.filter(r => r.method === 'thread/queue/start').length, 0);
  mode = 'wrong'; await assert.rejects(exec(process.execPath, [bin, '--apply', ...args], { env }));
  assert.deepEqual(await readdir(evidence), []);
  nativeId = 'queued-auto'; await prepareChannel('auto-drained', nativeId);
  mode = 'auto-drained';
  await assert.rejects(exec(process.execPath, [bin, '--apply', '--thread', thread, '--queue-id', nativeId, '--correlation', correlation, '--channel', 'auto-drained', '--generation', '1', '--evidence-root', evidence, '--graph-state', state], { env }));
  assert.equal(requests.filter(r => r.method === 'thread/queue/start').length, 0);
  const auto = (await call('channel', 'get', '--name', 'auto-drained')).channel;
  assert.equal(auto.queue[0].state, 'accepted'); assert.equal(auto.wakeReservation, undefined);
  assert.deepEqual(await readdir(evidence), []);
  nativeId = 'queued-payload'; await prepareChannel('payload', nativeId);
  mode = 'wrong-queue-payload';
  await assert.rejects(exec(process.execPath, [bin, '--apply', '--thread', thread, '--queue-id', nativeId, '--correlation', correlation, '--channel', 'payload', '--generation', '1', '--evidence-root', evidence, '--graph-state', state], { env }));
  assert.equal(requests.filter(r => r.method === 'thread/queue/start').length, 0);
  assert.equal((await call('channel', 'get', '--name', 'payload')).channel.wakeReservation.nativeQueueId, nativeId);
  assert.deepEqual(await readdir(evidence), []);
  nativeId = 'queued-1'; mode = 'success';
  const first = JSON.parse((await exec(process.execPath, [bin, '--apply', ...args], { env })).stdout);
  assert.equal(first.duplicate, false);
  const success = (await call('channel', 'get', '--name', 'success')).channel;
  assert.equal(success.wakeReservation, undefined);
  assert.equal(success.queue[0].wakeEvidence, first.evidence);
  assert.equal(first.settled, true);
  const verified = await verifyCodexWakeEvidence({ evidenceRoot: evidence, reference: first.evidence, session: `codex:${thread}` });
  assert.equal(verified.turn, turn);
  assert.equal(verified.correlation, correlation);
  assert.equal(verified.schema, 'agent-mesh.codex-wake-evidence.v4');
  assert.equal(verified.channel, 'success'); assert.equal(verified.generation, 1);
  assert.equal(requests.filter(r => r.method === 'thread/queue/start').length, 1);
  await assert.rejects(exec(process.execPath, [bin, '--apply', ...args], { env }));
  assert.equal(requests.filter(r => r.method === 'thread/queue/start').length, 1);
  const again = JSON.parse((await exec(process.execPath, [bin, '--publish', first.evidence, '--session', `codex:${thread}`, '--channel', 'success', '--evidence-root', evidence, '--graph-state', state], { env })).stdout);
  assert.equal(again.duplicate, true);
  assert.equal(again.settled, true);
  await prepareChannel('duplicate');
  await assert.rejects(call('channel', 'reserve-wake', '--name', 'duplicate', '--id', correlation, '--session', session, '--generation', '1', '--input', 'queued-1'));
  const feed = await call('query', 'changes', '--input', JSON.stringify({ sinceCursor: cursor }));
  assert.deepEqual(feed.events.filter(e => e.type === 'session.woken').map(e => e.evidence), [first.evidence]);
  const uncertainRoot = join(root, 'uncertain'); await mkdir(uncertainRoot, { mode: 0o700 });
  nativeId = 'queued-uncertain'; await prepareChannel('uncertain', nativeId);
  const uncertainArgs = ['--thread', thread, '--queue-id', nativeId, '--correlation', correlation, '--channel', 'uncertain', '--generation', '1', '--evidence-root', uncertainRoot, '--graph-state', state];
  mode = 'uncertain';
  await assert.rejects(exec(process.execPath, [bin, '--apply', ...uncertainArgs], { env }));
  await assert.rejects(call('channel', 'begin-handover', '--name', 'uncertain'));
  await prepareChannel('competing', nativeId);
  await assert.rejects(call('channel', 'reserve-wake', '--name', 'competing', '--id', correlation, '--session', session, '--generation', '1', '--input', nativeId));
  assert.deepEqual((await readdir(uncertainRoot)).map(name => name.split('-')[0]), ['intent']);
  const starts = requests.filter(r => r.method === 'thread/queue/start').length;
  await assert.rejects(exec(process.execPath, [bin, '--apply', ...uncertainArgs], { env }));
  assert.equal(requests.filter(r => r.method === 'thread/queue/start').length, starts);
  const recoverArgs = ['--reconcile', '--channel', 'uncertain', '--evidence-root', uncertainRoot, '--graph-state', state];
  await assert.rejects(exec(process.execPath, [bin, ...recoverArgs], { env }));
  const callsBeforeReconcile = requests.length;
  mode = 'success';
  await assert.rejects(exec(process.execPath, [bin, '--apply', ...recoverArgs], { env }));
  assert.equal(requests.length, callsBeforeReconcile);
  assert.ok((await call('channel', 'get', '--name', 'uncertain')).channel.wakeReservation);
  assert.equal(requests.filter(r => r.method === 'thread/queue/start').length, starts);
  const uncertainFeed = await call('query', 'changes', '--input', JSON.stringify({ sinceCursor: cursor }));
  assert.equal(uncertainFeed.events.filter(e => e.type === 'session.woken').length, 1);
  const partialRoot = join(root, 'partial'); await mkdir(partialRoot, { mode: 0o700 });
  nativeId = 'queued-partial'; await prepareChannel('partial', nativeId);
  const partialArgs = ['--thread', thread, '--queue-id', nativeId, '--correlation', correlation, '--channel', 'partial', '--generation', '1', '--evidence-root', partialRoot, '--graph-state', state];
  mode = 'partial';
  await assert.rejects(exec(process.execPath, [bin, '--apply', ...partialArgs], { env }));
  assert.deepEqual((await readdir(partialRoot)).map(name => name.split('-')[0]), ['intent']);
  const partialFeed = await call('query', 'changes', '--input', JSON.stringify({ sinceCursor: cursor }));
  assert.equal(partialFeed.events.filter(e => e.type === 'session.woken').length, 1);
  for (const mismatch of ['wrong-thread', 'wrong-turn', 'wrong-time', 'wrong-client', 'wrong-input']) {
    const mismatchRoot = join(root, mismatch); await mkdir(mismatchRoot, { mode: 0o700 });
    nativeId = `queued-${mismatch}`; await prepareChannel(mismatch, nativeId);
    const mismatchArgs = ['--thread', thread, '--queue-id', nativeId, '--correlation', correlation, '--channel', mismatch, '--generation', '1', '--evidence-root', mismatchRoot, '--graph-state', state];
    mode = mismatch;
    await assert.rejects(exec(process.execPath, [bin, '--apply', ...mismatchArgs], { env }));
    assert.deepEqual((await readdir(mismatchRoot)).map(name => name.split('-')[0]), ['intent']);
  }
  const mismatchFeed = await call('query', 'changes', '--input', JSON.stringify({ sinceCursor: cursor }));
  assert.equal(mismatchFeed.events.filter(e => e.type === 'session.woken').length, 1);
  // Simulate persisted draining state only; no operational cutover is enabled.
  const drainRoot = join(root, 'drain'); await mkdir(drainRoot, { mode: 0o700 });
  nativeId = 'queued-drain'; await prepareChannel('drain', nativeId);
  let graphState = await call('show', '--json');
  const draining = graphState.channels.find(item => item.id === 'drain');
  draining.phase = 'draining'; draining.handover = { predecessor: 'codex:old-fixture', previousGeneration: 0, successor: session, backlog: [correlation] };
  await appendFile(join(state, 'events.jsonl'), `${JSON.stringify({ schema: 'agent-mesh.session-graph-event.v1', id: 'fixture-drain', type: 'channel.updated', at: new Date().toISOString(), channel: draining, seq: graphState.lastSeq + 1, host: 'local' })}\n`);
  const drainArgs = ['--thread', thread, '--queue-id', nativeId, '--correlation', correlation, '--channel', 'drain', '--generation', '1', '--evidence-root', drainRoot, '--graph-state', state];
  mode = 'uncertain'; await assert.rejects(exec(process.execPath, [bin, '--apply', ...drainArgs], { env }));
  const callsBeforeRecovery = requests.filter(r => r.method === 'thread/queue/start').length;
  mode = 'success';
  await assert.rejects(exec(process.execPath, [bin, '--apply', '--reconcile', '--channel', 'drain', '--evidence-root', drainRoot, '--graph-state', state], { env }));
  const drained = (await call('channel', 'get', '--name', 'drain')).channel;
  assert.equal(drained.queue[0].state, 'accepted'); assert.ok(drained.wakeReservation);
  assert.equal(requests.filter(r => r.method === 'thread/queue/start').length, callsBeforeRecovery);
  // Both unbound v3 and bound v4 recovery receipts fail closed, even with a valid digest.
  for (const bound of [false, true]) {
    const old = { schema: `agent-mesh.codex-wake-evidence.v${bound ? 4 : 3}`, source: `codex-app-server.correlated-recovery${bound ? '-bound' : ''}`, session, queueId: nativeId, correlation, turn, startedAt: 123456789, ...(bound ? { channel: 'drain', generation: 1, payloadSha256: createHash('sha256').update('fixture').digest('hex') } : {}) };
    const body = `${JSON.stringify(old)}\n`, digest = createHash('sha256').update(body).digest('hex');
    await writeFile(join(drainRoot, `wake-${digest}.json`), body, { mode: 0o600 });
    await assert.rejects(verifyCodexWakeEvidence({ evidenceRoot: drainRoot, reference: `codex-wake:${digest}`, session }), /identity mismatch/);
  }
  // Readback alone cannot distinguish a queued item from a steered message.
  const autoRoot = join(root, 'auto-proof'); await mkdir(autoRoot, { mode: 0o700 });
  nativeId = 'queued-auto-proof'; await prepareChannel('auto-proof', nativeId);
  const autoArgs = ['--observe-auto', '--thread', thread, '--queue-id', nativeId, '--correlation', correlation, '--channel', 'auto-proof', '--generation', '1', '--evidence-root', autoRoot, '--graph-state', state];
  const callsBeforeAuto = requests.length;
  await assert.rejects(exec(process.execPath, [bin, '--apply', ...autoArgs], { env }));
  assert.equal(requests.length, callsBeforeAuto);
  const autoState = (await call('channel', 'get', '--name', 'auto-proof')).channel;
  assert.equal(autoState.queue[0].state, 'accepted');
  assert.equal(autoState.wakeReservation, undefined);
  assert.deepEqual(await readdir(autoRoot), []);
  await assert.rejects(call('channel', 'reserve-wake', '--name', 'auto-proof', '--id', correlation, '--session', session, '--generation', '1', '--input', nativeId, '--source', 'auto-readback'));
  const oldProof = { schema: 'agent-mesh.codex-wake-evidence.v5', source: 'codex-app-server.auto-start-bound-readback', session, queueId: nativeId, correlation, turn, startedAt: 123456789, channel: 'auto-proof', generation: 1, payloadSha256: createHash('sha256').update('fixture').digest('hex') };
  const oldBody = `${JSON.stringify(oldProof)}\n`, oldDigest = createHash('sha256').update(oldBody).digest('hex');
  await writeFile(join(autoRoot, `wake-${oldDigest}.json`), oldBody, { mode: 0o600 });
  await assert.rejects(verifyCodexWakeEvidence({ evidenceRoot: autoRoot, reference: `codex-wake:${oldDigest}`, session }), /identity mismatch/);
  const delayedRoot = join(root, 'delayed'); await mkdir(delayedRoot, { mode: 0o700 });
  nativeId = 'queued-delayed'; await prepareChannel('delayed', nativeId); mode = 'null-start';
  const beforeDelayed = requests.filter(r => r.method === 'thread/queue/start').length;
  const delayed = JSON.parse((await exec(process.execPath, [bin, '--apply', '--thread', thread, '--queue-id', nativeId, '--correlation', correlation, '--channel', 'delayed', '--generation', '1', '--evidence-root', delayedRoot, '--graph-state', state], { env })).stdout);
  assert.equal((await verifyCodexWakeEvidence({ evidenceRoot: delayedRoot, reference: delayed.evidence, session })).startedAt, 123456789);
  assert.equal(requests.filter(r => r.method === 'thread/queue/start').length, beforeDelayed + 1);
  assert.ok(delayedReads >= 2);
  const file = join(evidence, `wake-${first.evidence.slice('codex-wake:'.length)}.json`);
  const saved = JSON.parse(await readFile(file, 'utf8')); saved.startedAt++;
  await writeFile(file, `${JSON.stringify(saved)}\n`);
  await assert.rejects(verifyCodexWakeEvidence({ evidenceRoot: evidence, reference: first.evidence, session: `codex:${thread}` }), /digest/);
});
